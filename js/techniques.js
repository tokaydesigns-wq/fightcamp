/* ---------- 4-week program ---------- */

// Each week has a title, goal and items built from the technique's drills.
// who = the fighter name, used in the "study" step.
function buildPlan(t, who) {
  const tag = (kind, list, dose) => list.map(d => ({ kind, text: d, dose }));
  const study = who ? `Watch 3 clips of ${who} doing it` : 'Watch 3 clips of a top fighter doing it';
  return [
    { title: 'Week 1: Learn the shape', goal: 'Slow, perfect reps. Speed comes later.', items: [
      { kind: 'Study', text: study, dose: `Look for: ${t.keys[0].toLowerCase()}` },
      ...tag('Solo', t.solo, '3 rounds × 2 min, slow'),
      { kind: 'Check', text: 'Film one round and compare it to the key points', dose: 'Pick 1 thing to fix' } ] },
    { title: 'Week 2: Add speed and power', goal: 'Same shape, now at full speed and on the move.', items: [
      ...tag('Solo', t.solo, '3 rounds × 3 min, full speed'),
      ...tag('Equipment', t.gear, '3 rounds × 3 min') ] },
    { title: 'Week 3: With a partner', goal: 'Make it work on someone who moves and reacts.', items: [
      ...tag('Partner', t.partner, '4 rounds × 3 min'),
      ...tag('Equipment', t.gear.slice(0, 1), '2 rounds, hardest effort') ] },
    { title: 'Week 4: Use it live', goal: 'Bring it into sparring or rolling, at a controlled pace.', items: [
      ...tag('Partner', t.partner.slice(-1), '3 rounds × 3 min'),
      ...tag('Live', t.live, '3 to 5 rounds'),
      { kind: 'Check', text: 'Film a live round and count your attempts', dose: 'Compare with week 1' } ] },
  ];
}
